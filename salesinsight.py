#RF03 – Tratar os Dados (datetime)

def tratar_dados(df):
  """Trata o DataFrame de vendas:

  1. Remove espaços extras em colunas de texto.
  2. Converte 'data_venda' para datetime e descarta datas inválidas.
  3. Converte 'quantidade' para int e 'preco_unitario' para float.
  4. Exibe e retorna o relatório de limpeza.
  """


  df_limpo = df.copy()
  qtd_inicial = len(df_limpo)

  # 1. Remover espaços extras em colunas de texto (tipo 'object')
  colunas_texto = df_limpo.select_dtypes(include=["object"]).columns
  for col in colunas_texto:
    df_limpo[col] = df_limpo[col].astype(str).str.strip()

  # 2. Converter data_venda para datetime (invalidos passam a ser NaT)
  df_limpo["data_venda"] = pd.to_datetime(
      df_limpo["data_venda"], errors="coerce"
  )

  # Contar quantos registros eram datas inválidas
  qtd_datas_invalidas = df_limpo["data_venda"].isnull().sum()

  # Descartar linhas onde a data virou NaT
  df_limpo = df_limpo.dropna(subset=["data_venda"]).reset_index(drop=True)

  # 3. Garantir os tipos numéricos corretos
  df_limpo["quantidade"] = df_limpo["quantidade"].astype(int)
  df_limpo["preco_unitario"] = df_limpo["preco_unitario"].astype(float)

  qtd_final = len(df_limpo)

  # 4. Montar e exibir o relatório de limpeza
  relatorio = {
      "registros_iniciais": qtd_inicial,
      "datas_invalidas_removidas": qtd_datas_invalidas,
      "registros_finais": qtd_final,
  }

  print("RELATÓRIO DE LIMPEZA E TRATAMENTO:")
  print(f"\nRegistros recebidos: {relatorio['registros_iniciais']}")
  print(
      "Datas inválidas removidas:"
      f" {relatorio['datas_invalidas_removidas']}"
  )
  print(f"Registros válidos restantes: {relatorio['registros_finais']}")

  return df_limpo, relatorio

