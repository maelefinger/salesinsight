#RF05 – Calcular Métricas Agregadas com groupby
import pandas as pd


def calcular_metricas(df):
  """Calcula as métricas agregadas do dataset (RF05).

  Retorna um dicionário no formato {nome_da_metrica: DataFrame}:
  - por_mes: receita total, quantidade e número de vendas por mês
  - top_produtos: top 5 produtos por receita total
  - por_categoria: receita total por categoria
  - por_regiao: receita total e ticket médio por região
  """
  metricas = {}

  # 1. Agregação Por Mês (Receita Total, Quantidade e Nº de Vendas)
  por_mes = (
      df.groupby(["mes"])
      .agg(
          receita_total=("receita_total", "sum"),
          quantidade=("quantidade", "sum"),
          n_vendas=("id_venda", "count"),
      )
      .reset_index()
  )
  metricas["por_mes"] = por_mes

  # 2. Top 5 Produtos por Receita Total
  top_produtos = (
      df.groupby("produto")
      .agg(receita_total=("receita_total", "sum"))
      .sort_values(by="receita_total", ascending=False)
      .head(5)
      .reset_index()
  )
  metricas["top_produtos"] = top_produtos

  # 3. Agregação Por Categoria
  por_categoria = (
      df.groupby("categoria")
      .agg(receita_total=("receita_total", "sum"))
      .sort_values(by="receita_total", ascending=False)
      .reset_index()
  )
  metricas["por_categoria"] = por_categoria

  # 4. Agregação Por Região (Receita Total e Ticket Médio)
  por_regiao = (
      df.groupby("regiao")
      .agg(
          receita_total=("receita_total", "sum"),
          ticket_medio=("receita_total", "mean"),
      )
      .sort_values(by="receita_total", ascending=False)
      .reset_index()
  )
  # Arredondar valores decimais monetários
  por_regiao["ticket_medio"] = por_regiao["ticket_medio"].round(2)
  metricas["por_regiao"] = por_regiao

  # Exibição formatada no console
  print("\n")
  print("MÉTRICAS AGREGADAS:")
  print("\n")

  for chave, df_metrica in metricas.items():
    print(f"\n {chave.upper().replace('_', ' ')}:\n")
    print(df_metrica.to_string(index=False))

  return metricas

  # Executa as agregações do RF05
dicionario_metricas = calcular_metricas(df_transformado)

#RF06 – Segmentar Clientes por Nível de Gasto

def segmentar_clientes(df):
  """Agrupa por cliente, calcula o total gasto e classifica em Bronze, Prata e Ouro.

  Utiliza função lambda com .apply() conforme requisito.
  """
  # 1. Agrupar por cliente e somar a receita total
  df_clientes = (
      df.groupby("cliente")
      .agg(total_gasto=("receita_total", "sum"))
      .sort_values(by="total_gasto", ascending=False)
      .reset_index()
  )

  # Arredondar valores para 2 casas decimais
  df_clientes["total_gasto"] = df_clientes["total_gasto"].round(2)

  # 2. Classificação usando Função Lambda com .apply()
  df_clientes["segmento"] = df_clientes["total_gasto"].apply(
      lambda gasto: (
          "Ouro" if gasto > 15000 else ("Prata" if gasto >= 5000 else "Bronze")
      )
  )

  # 3. Exibição dos resultados no console
  print("\n")
  print("SEGMENTAÇÃO DE CLIENTES:")

  print("\nTop 10 Maiores Clientes:\n")
  print(df_clientes.head(10).to_string(index=False))

  print("\nDistribuição de Clientes por Segmento:\n")
  print(df_clientes["segmento"].value_counts().to_string())

  return df_clientes

  # Executa a segmentação de clientes
df_clientes_segmentados = segmentar_clientes(df_transformado)

