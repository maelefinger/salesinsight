#RF04 – Criar Colunas Derivadas com Transformações Condicionais

def criar_colunas_derivadas(df):
  """Cria colunas derivadas para análise de vendas.

  - receita_total: quantidade * preco_unitario
  - mes, mes_nome, trimestre, ano: componentes temporais da data_venda
  - faixa_receita_item: classificação condicional da receita por linha
  """
  df_trans = df.copy()

  # 1. Receita total por linha (operação vetorizada)
  df_trans["receita_total"] = (
      df_trans["quantidade"] * df_trans["preco_unitario"]
  ).round(2)

  # 2. Componentes temporais da data (.dt)
  df_trans["mes"] = df_trans["data_venda"].dt.month
  df_trans["ano"] = df_trans["data_venda"].dt.year
  df_trans["trimestre"] = df_trans["data_venda"].dt.quarter.apply(
      lambda q: f"Q{q}"
  )

  # Mapeamento do número do mês para o nome em português
  meses_pt = {
      1: "Janeiro",
      2: "Fevereiro",
      3: "Março",
      4: "Abril",
      5: "Maio",
      6: "Junho",
      7: "Julho",
      8: "Agosto",
      9: "Setembro",
      10: "Outubro",
      11: "Novembro",
      12: "Dezembro",
  }
  df_trans["mes_nome"] = df_trans["mes"].map(meses_pt)

  # 3. Transformação condicional para a Faixa de Receita do Item
  df_trans["faixa_receita_item"] = "Não Classificado"

  condicoes = [
      df_trans["receita_total"] < 500,
      (df_trans["receita_total"] >= 500) & (df_trans["receita_total"] < 5000),
      df_trans["receita_total"] >= 5000,
  ]
  faixas = ["Baixo Valor", "Medio Valor", "Alto Valor"]

  for condicao, faixa in zip(condicoes, faixas):
    df_trans.loc[condicao, "faixa_receita_item"] = faixa

  print("\n")
  print("COLUNAS DERIVADAS CRIADAS COM SUCESSO:")
  print("\n")
  print(
      "Novas colunas adicionadas:"
      " ['receita_total', 'mes', 'mes_nome', 'trimestre', 'ano',"
      " 'faixa_receita_item']"
  )

  return df_trans


