import pandas as pd

def processar_coluna(df, coluna, funcao_transformacao, nome_saida=None):
  """Aplica uma função de transformação a uma coluna do DataFrame.

  Demonstra o conceito de Função de Ordem Superior,
  recebendo uma função como argumento.
  """
  df_mod = df.copy()
  nome_saida = nome_saida or f"{coluna}_transformado"

  # Aplica a função recebida como parâmetro na coluna indicada
  df_mod[nome_saida] = df_mod[coluna].apply(funcao_transformacao)
  return df_mod


